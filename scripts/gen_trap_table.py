import json, re
T = json.load(open('work/traps.json'))
SZ2 = {'bool','Boolean','char','unsigned char','signed char','short','unsigned short','int16_t','uint16_t','INTEGER','OSErr','SInt16','UInt16','Byte','SignedByte','OSStatus16','ResID','ScriptCode','StyleParameter','CharParameter','Style','WindowPartCode'}
def size(t):
    t = t.replace('const ','').strip()
    if t == 'void': return 0
    if t.endswith('*'): return 4
    if t in SZ2: return 2
    return 4
out = ['/* generated by scripts/gen_trap_table.py - do not edit */','#include "trapnames.h"','const TrapInfo trap_info[] = {']
rows = []
for k, (name, ret, args, mgr) in sorted(T.items(), key=lambda kv: int(kv[0],16)):
    num = int(k,16)
    stack = all(a[2] is None for a in args)
    ab = sum(max(2,size(a[1])) for a in args) if stack else -1
    rb = size(ret) if stack else 0
    if num & 0x0800 == 0: ab = -1   # OS trap: register-based
    rows.append(f'  {{0x{num:04X}, "{name}", {ab}, {rb}}},')
out += rows + ['  {0, 0, 0, 0}','};']
open('port/src/trapnames.c','w').write('\n'.join(out)+'\n')
open('port/src/trapnames.h','w').write('typedef struct { unsigned short trap; const char *name; int argbytes; int retbytes; } TrapInfo;\nextern const TrapInfo trap_info[];\n')
print(len(rows), 'rows')
