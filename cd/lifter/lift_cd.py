#!/usr/bin/env python3
"""68k -> C translation of the CD release's CODE 1, reusing the floppy lifter (tools/lift.py, tools/analyze.py).
The CD program is one big CodeWarrior segment (resource bytes loaded at a fixed guest address) with no relocations.
Output: cd/gen/lift_cd1.c, cd/gen/lift_cd_tab.c   (generated; never overwrites port/gen)."""
import sys, os, json, struct, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze, lift

_H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(_H)) if os.path.basename(_H) == 'lifter' else os.path.dirname(_H)
CODE = os.path.join(ROOT, 'cd', 'extracted', 'app', 'CODE')
OUT = os.path.join(ROOT, 'cd', 'gen')
RSRC = None
analyze.SEGBASE = lambda n: 0x100000 + n * 0x40000          # CODE 1 is 210 KB: the floppy spacing (64 KB) would overlap
analyze.SWITCH_WORD = analyze.SWITCH_LONG = analyze.SWITCH_RANGE = -1

def code1_from_rsrc(path):
    """read CODE id 1 out of a resource-fork file"""
    d = open(path, 'rb').read(); doff, moff, dlen, mlen = struct.unpack('>IIII', d[:16]); m = d[moff:moff + mlen]
    tl = struct.unpack('>H', m[24:26])[0]; ntypes = struct.unpack('>H', m[tl:tl + 2])[0] + 1
    for i in range(ntypes):
        t, cnt, ro = struct.unpack('>4sHH', m[tl + 2 + i * 8:tl + 10 + i * 8])
        if t == b'CODE':
            for k in range(cnt + 1):
                e = m[tl + ro + k * 12:tl + ro + k * 12 + 12]; rid = struct.unpack('>h', e[:2])[0]; off = struct.unpack('>I', b'\0' + e[5:8])[0]
                if rid == 1: n = struct.unpack('>I', d[doff + off:doff + off + 4])[0]; return d[doff + off + 4:doff + off + 4 + n]
    sys.exit('no CODE 1 resource in ' + path)

def build():
    P = analyze.Prog(); P.M = None
    c1 = code1_from_rsrc(RSRC) if RSRC else open(os.path.join(CODE, '1.bin'), 'rb').read()
    P.mem = {1: c1}; P.segbase = {1: analyze.SEGBASE(1)}; P.img = {}
    P.jt = {0: analyze.SEGBASE(1) + 4}; P.jt_a5off = {0x22: analyze.SEGBASE(1) + 4}
    return P
analyze.build = build
def find_extra(P):
    ex = set()
    for a, i in P.insts.items():
        if i.mn in ('pea', 'lea'):
            for op in i.ops:
                if isinstance(op, tuple) and op[0] == 'pcd' and op[2] not in P.funcs and op[2] not in P.insts:
                    try: j = analyze.fetch(P, op[2])
                    except Exception: j = None
                    if j is not None: ex.add(op[2])
    m = P.mem[1]; base = analyze.SEGBASE(1)
    for o in range(4, len(m) - 4, 2):
        a = base + o
        if a not in P.insts and struct.unpack_from('>H', m, o)[0] == 0x4E56: ex.add(a)
    return ex
analyze.find_extra = find_extra

def gen():
    P = analyze.build(); analyze.analyze(P)
    RJ = json.load(open(os.path.join(ROOT, 'cd', 'relocs.json')))
    import hashlib
    if hashlib.md5(P.mem[1]).hexdigest() != RJ['md5']: sys.exit('CODE 1 differs from the release the relocation list was made for (cd/relocs.json); not translating')
    G = lift.Gen(P, {'1': RJ['relocs']}); G.mids = []
    entries = set(P.funcs); os.makedirs(OUT, exist_ok=True)
    funcs = sorted(e for e in P.funcs if G.seg_off(e))
    parts = ['#define LSEG 1', '#include "../../port/liftrt.h"', '#include "lift_cd_protos.h"', '/* generated by tools/lift_cd.py -- do not edit */']
    tabs = []; protos = []; tot = bails = 0
    for e in funcs:
        try: t, b = G.emit_function(e, P.funcs[e], entries)
        except Exception as ex: print('FAILED function %x: %r' % (e, ex), file=sys.stderr); continue
        parts.append(t); tot += 1; bails += b; protos.append('void %s(void);' % G.fname(e)); tabs.append((e - analyze.SEGBASE(1), G.fname(e))) if e - analyze.SEGBASE(1) >= 0x400 else None      # below 0x400: CodeWarrior start-up glue (runs once, odd control flow): stays interpreted
    open(os.path.join(OUT, 'lift_cd1.c'), 'w').write('\n'.join(parts) + '\n')
    open(os.path.join(OUT, 'lift_cd_protos.h'), 'w').write('#include "../../port/liftrt.h"\n' + '\n'.join(protos) + '\n')
    with open(os.path.join(OUT, 'lift_cd_tab.c'), 'w') as f:
        f.write('#include "../../port/liftrt.h"\n#include "lift_cd_protos.h"\nconst LiftEnt lift_ents[] = {\n')
        for off, n in tabs: f.write('  {1, 0x%x, %s},\n' % (off, n))
        f.write('};\nconst int lift_nents = %d;\nconst LiftMid lift_mids[] = {\n' % len(tabs))
        for sid, off, n, hl in G.mids:
            if off >= 0x400: f.write('  {%d, 0x%x, %s, %d},\n' % (sid, off, n, hl))
        f.write('};\nconst int lift_nmids = %d;\n' % len(G.mids))
        f.write('const unsigned char lift_mdrv_sig[16] = {0}; const unsigned lift_mdrv_len = 0;\nconst unsigned char lift_smod_sig[16] = {0}; const unsigned lift_smod_len = 0;\n')
    print('functions: %d, instructions bailed: %d' % (tot, bails))

if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == 'gen':
    if len(sys.argv) > 2: RSRC = sys.argv[2]; OUT = sys.argv[3] if len(sys.argv) > 3 else OUT
    gen(); sys.exit(0)
if __name__ == '__main__':
    P = analyze.build(); analyze.analyze(P)
    tot = len(P.mem[1]); cov = sum(i.size for i in P.insts.values())
    print('functions:', len(P.funcs), 'instructions:', len(P.insts), 'covered %d of %d bytes (%.0f%%)' % (cov, tot, 100.0 * cov / tot))
    print('warnings:', len(P.warnings), collections.Counter(w[0] for w in P.warnings))
    print('indirect calls:', len(P.ind_calls), ' indirect jumps:', len(P.ind_jumps), ' jmp tables:', len(P.jmp_tables))
    for a, t in P.ind_jumps[:12]: print('   %x %s' % (a - analyze.SEGBASE(1), t))
