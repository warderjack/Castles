#!/usr/bin/env python3
"""Pre-rasterize replacement bitmap fonts (Liberation Sans/Serif/Mono, SIL OFL) into fontdata.h.
Strikes: family x {plain,bold} x pixel sizes. Glyph = (advance, left bearing, width, height, top-ascent offset, bitmap rows)."""
from PIL import Image, ImageDraw, ImageFont
import sys
FAM = {
 'sans':  ('/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf','/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'),
 'serif': ('/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf','/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf'),
 'mono':  ('/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf','/usr/share/fonts/truetype/liberation/LiberationMono-Bold.ttf'),
}
SIZES = [9,10,12,14,16,18,20,24,28,36,48]
chars = [bytes([c]).decode('mac_roman') if c>=32 and c!=127 else ' ' for c in range(256)]
out = []; strikes = []
blob = bytearray()
for fam,(reg,bold) in FAM.items():
    for b,path in enumerate((reg,bold)):
        for sz in SIZES:
            f = ImageFont.truetype(path, sz)
            asc, desc = f.getmetrics()
            glyphs = []
            for c in range(256):
                ch = chars[c]
                adv = int(round(f.getlength(ch)))
                if c < 32 or c == 127: adv = 0
                im = Image.new('L', (sz*3, sz*3), 0); d = ImageDraw.Draw(im)
                d.fontmode = '1'   # no antialias
                d.text((sz, sz), ch, font=f, fill=255, anchor='ls')  # baseline at y=sz
                bb = im.point(lambda v: 255 if v>127 else 0).getbbox()
                if not bb or ch == ' ':
                    glyphs.append((adv,0,0,0,0,b'')); continue
                l,t,r,bt = bb; w=r-l; h=bt-t
                rb = (w+7)//8; rows = bytearray()
                px = im.load()
                for y in range(t,bt):
                    for xb in range(rb):
                        v=0
                        for k in range(8):
                            x=l+xb*8+k
                            if x<r and px[x,y]>127: v|=0x80>>k
                        rows.append(v)
                glyphs.append((adv, l-sz, w, h, sz-t, bytes(rows)))   # left bearing, ascent of top above baseline
            off = len(blob)
            tbl = []
            for (adv,lb,w,h,top,rows) in glyphs:
                tbl.append((adv,lb,w,h,top,len(blob))); blob += rows
            strikes.append((fam,b,sz,asc,desc,tbl))
with open('../fontdata.h','w') as o:
    o.write('/* generated by gen/genfont.py from Liberation fonts (SIL OFL 1.1) */\n')
    o.write('typedef struct { int16_t adv, lb, w, h, top; uint32_t off; } FGlyph;\n')
    o.write('typedef struct { int fam, bold, size, ascent, descent; const FGlyph *g; } FStrike;\n')
    o.write('static const uint8_t font_blob[%d] = {' % len(blob))
    o.write(','.join(str(x) for x in blob)); o.write('};\n')
    for i,(fam,b,sz,asc,desc,tbl) in enumerate(strikes):
        o.write('static const FGlyph fg_%d[256] = {' % i + ','.join('{%d,%d,%d,%d,%d,%d}'%t for t in tbl) + '};\n')
    fid = {'sans':0,'serif':1,'mono':2}
    o.write('static const FStrike font_strikes[%d] = {' % len(strikes))
    o.write(','.join('{%d,%d,%d,%d,%d,fg_%d}'%(fid[fam],b,sz,asc,desc,i) for i,(fam,b,sz,asc,desc,tbl) in enumerate(strikes)))
    o.write('};\n#define N_FSTRIKES %d\n' % len(strikes))
print('strikes',len(strikes),'blob',len(blob))
